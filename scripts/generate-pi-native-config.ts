import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

/** Pin the native read-only config contract; never copy the native config writers or connection runtime. */
export function renderPiNativeConfig(root = resolve(import.meta.dir, "..")): string {
  const sdk = dirname(Bun.resolveSync("@earendil-works/pi-coding-agent", join(root, "packages/adapter-pi/src")));
  const pkg = JSON.parse(readFileSync(join(sdk, "../package.json"), "utf8"));
  if (pkg.version !== "1.0.0" || pkg.license !== "MIT" || pkg.piConfig?.configDir !== ".pi") throw new Error("Pi native configuration requires review before updating its pinned contract.");
  const validators = readFileSync(join(sdk, "core/mcp-servers.js"), "utf8");
  const config = readFileSync(join(sdk, "extensions/mcp/config.js"), "utf8");
  const digest = createHash("sha256").update(validators).update("\0").update(config).digest("hex");
  const validationCode = validators.slice(0, validators.indexOf("export class McpServerRegistry"));
  const configCode = config.slice(config.indexOf("function isRecord(value)"), config.indexOf("/**\n * Change one server's settings"))
    .replaceAll("isRecord", "isConfigRecord");
  if (!validationCode.includes("export function validateMcpServerConfig") || !configCode.includes("export function loadMcpConfig") || configCode.includes("writeFileSync")) throw new Error("Pi config extraction contract changed.");
  return `// @ts-nocheck\n// Generated by scripts/generate-pi-native-config.ts; do not edit.\n// @earendil-works/pi-coding-agent 1.0.0 (MIT); https://github.com/earendil-works/pi\n// native-source-sha256:${digest}\nimport { existsSync, readFileSync } from "node:fs";\nimport { join } from "node:path";\nconst CONFIG_DIR_NAME = ".pi";\n${validationCode}\n${configCode}`;
}

if (import.meta.main) writeFileSync(resolve(import.meta.dir, "../packages/adapter-pi/src/pi-extensions/tool-policy/native-config.pinned.ts"), renderPiNativeConfig());
