import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { buildSessionSchemas } from "../packages/core/src/session/schema";

const root = resolve(import.meta.dir, "..");
export const SESSION_SCHEMA_OUTPUT = "packages/core/src/session/schema.generated.ts";

export function renderSessionSchemasModule(): string {
  const { event, command } = buildSessionSchemas();
  const eventJson = JSON.stringify(event, null, 2);
  const commandJson = JSON.stringify(command, null, 2);
  const digest = createHash("sha256").update(eventJson).update("\n").update(commandJson).digest("hex");
  return [
    "// GENERATED by scripts/generate-session-schemas.ts. Do not edit by hand.",
    `export const SESSION_EVENT_SCHEMA = ${eventJson} as const;`,
    `export const SESSION_COMMAND_SCHEMA = ${commandJson} as const;`,
    `export const SESSION_SCHEMA_DIGEST = ${JSON.stringify(digest)};`,
    "",
  ].join("\n");
}

/** Idempotent: rewrites the file only when content differs. Returns true when it changed. */
export async function generateSessionSchemas(projectRoot = root): Promise<boolean> {
  const target = resolve(projectRoot, SESSION_SCHEMA_OUTPUT);
  const next = renderSessionSchemasModule();
  let current = "";
  try { current = readFileSync(target, "utf-8"); } catch { /* first generation */ }
  if (current === next) return false;
  writeFileSync(target, next);
  return true;
}

if (import.meta.main) {
  const changed = await generateSessionSchemas();
  console.log(`session schemas ${changed ? "written" : "unchanged"}: ${SESSION_SCHEMA_OUTPUT}`);
}
